def _table_is_empty(db_path, table_name):
    conn = sqlite3.connect(db_path)
    try:
        return conn.execute(f"SELECT COUNT(*) FROM {table_name}").fetchone()[0] == 0
    finally:
        conn.close()


def _bootstrap_local_data():
    """First-run (and self-healing) setup for the local SQLite tier.

    data/finance.db and the CSVs it's built from are gitignored on purpose
    (they're generated artifacts, not source) -- which means a fresh clone,
    or a fresh deploy on something like Streamlit Community Cloud, starts
    with no database at all. Cloud deploy platforms only run
    `streamlit run dashboard/app.py`; there's no hook to run a setup script
    first. So: if the SQLite backend is selected and the database simply
    isn't there yet, run the full local pipeline once, automatically -- the
    same four steps the README asks you to run by hand locally (generate,
    load, detect anomalies, forecast). This is what makes "clone and run" or
    "open the deployed link" actually work with zero manual setup, instead
    of failing on a database that was never allowed into git to begin with.

    The ML backfill is checked separately from "does the db file exist,"
    not folded into the same guard -- Streamlit Community Cloud's redeploy
    on a git push pulls new code into the *same* running environment rather
    than starting from a truly fresh clone, so a database generated by an
    earlier deploy (before the ML steps were added here) sticks around
    across a code-only push. A single `if LOCAL_DB_PATH.exists(): return`
    would then skip the ML steps forever on that already-running deploy,
    even though the code now expects them -- which is exactly what happened
    the first time this shipped: the Anomalies and 30-Day Forecast sections
    silently rendered "nothing yet" in production even though the pipeline
    logic itself was fine. Checking the ML tables independently means this
    self-heals on the very next load, no manual reboot required.
    """
    repo_root = Path(__file__).parent.parent

    if not LOCAL_DB_PATH.exists():
        with st.spinner("First run: generating sample data..."):
            subprocess.run(
                [sys.executable, str(repo_root / "data" / "generate_data.py")],
                check=True, cwd=repo_root,
            )
            subprocess.run(
                [sys.executable, str(repo_root / "etl" / "load_to_db.py")],
                check=True, cwd=repo_root,
            )

    needs_ml = (
        _table_is_empty(LOCAL_DB_PATH, "ml_anomaly_flags")
        or _table_is_empty(LOCAL_DB_PATH, "ml_cashflow_forecast")
    )
    if needs_ml:
        with st.spinner("Running anomaly detection and cash-flow forecasting..."):
            subprocess.run(
                [sys.executable, str(repo_root / "ml" / "detect_anomalies.py")],
                check=True, cwd=repo_root,
            )
            subprocess.run(
                [sys.executable, str(repo_root / "ml" / "forecast_cashflow.py")],
                check=True, cwd=repo_root,
            )


