def main():
    with st.sidebar:
        st.caption(f"Logged in as **{st.session_state.get('name', _username)}**")
        _authenticator.logout("Log out", "sidebar")
        # logout() doesn't rerun on its own, so without this, the rest of
        # this page keeps rendering with stale (now-invalid) auth state for
        # one more pass before the login gate reappears on the next
        # interaction. Rerunning immediately makes "Log out" feel instant.
        if not st.session_state.get("authentication_status"):
            st.session_state.pop("_post_login_rerun_done", None)
            st.rerun()

    st.title("\U0001F4B0 CashPulse")
    st.caption("Personal & SME finance health monitor")

    if not backend_ready():
        if BACKEND == "sqlite":
            st.error("No database found. Run `python data/generate_data.py` then "
                      "`python etl/load_to_db.py` first.")
        else:
            st.error("Could not connect to Postgres via DATABASE_URL. Run "
                      "`python cloud/pipeline/run_pipeline.py` first, and check "
                      f"cloud/.env. Error: {st.session_state.get('_connection_error')}")
        return

    accounts = load_table("accounts")

    # Restrict which accounts this login can see. "*" means full access
    # (the "demo" login); anything else is an exact list of account names --
    # this is what makes "Authentication" in the roadmap mean more than
    # just a locked door: different logins genuinely see different data,
    # the way real multi-tenant access control would.
    allowed = st.secrets["auth"]["account_access"].get(_username, [])
    if "*" not in allowed:
        accounts = accounts[accounts["account_name"].isin(allowed)]
    if accounts.empty:
        st.error(f"No accounts are configured for **{_username}** in "
                  "`st.secrets['auth']['account_access']`. Contact whoever set up this deploy.")
        st.stop()

    source_label, txn_count, freshness = get_data_status()

    # --- Toolbar: account picker + live data badge -----------------------
    with st.container(border=True):
        tb1, tb2, tb3 = st.columns([2, 1, 3])
        with tb1:
            account_name = st.selectbox("Account", accounts["account_name"])
        with tb2:
            st.write("")
            if st.button("↻ Refresh data"):
                load_table.clear()
                get_data_status.clear()
                st.rerun()
        with tb3:
            st.write("")
            st.caption(f"🟢 **{source_label}** · **{txn_count:,}** real transactions loaded "
                       f"· {freshness}")

    account_id = int(accounts.loc[accounts["account_name"] == account_name, "account_id"].iloc[0])

    health = load_table("health", {"account_id": account_id})
    monthly = load_table("monthly", {"account_id": account_id})
    forecast = load_table("forecast", {"account_id": account_id})
    category_spend = load_table("category_spend", {"account_id": account_id})
    anomalies = load_table("anomalies", {"account_id": account_id})
    budget_vs_actual = load_table("budget_vs_actual", {"account_id": account_id})
    recurring = load_table("recurring", {"account_id": account_id})

    # --- KPI row -----------------------------------------------------------
    current_balance = float(health["current_balance"].iloc[0]) if not health.empty else 0.0
    avg_daily_burn = float(health["avg_daily_burn"].iloc[0]) if not health.empty else 0.0
    runway_days = (current_balance / avg_daily_burn) if avg_daily_burn > 0 else float("inf")
    last_month_net = float(monthly["net_flow"].iloc[-1]) if not monthly.empty else 0.0

    if runway_days == float("inf"):
        runway_text, runway_delta, runway_color = "∞", "no burn detected", "normal"
    elif runway_days < 60:
        runway_text, runway_delta, runway_color = f"{runway_days:,.0f} days", "below 60-day buffer", "inverse"
    else:
        runway_text, runway_delta, runway_color = f"{runway_days:,.0f} days", "healthy buffer", "normal"

    net_flow_delta = "inflow" if last_month_net >= 0 else "outflow"
    net_flow_color = "normal" if last_month_net >= 0 else "inverse"

    col1, col2, col3, col4 = st.columns(4)
    col1.metric("Current Balance", f"${current_balance:,.0f}")
    col2.metric("Avg Daily Burn (30d)", f"${avg_daily_burn:,.0f}")
    col3.metric("Runway", runway_text, delta=runway_delta, delta_color=runway_color)
    col4.metric("Last Month Net Flow", f"${last_month_net:,.0f}", delta=net_flow_delta, delta_color=net_flow_color)

    if runway_days < 60:
        st.warning(f"⚠️ At the current burn rate, this account has an estimated "
                    f"{runway_days:,.0f}-day runway. Consider reviewing discretionary spend below.")

    # --- Prescriptive recommendations ---------------------------------------
    # The roadmap's own framing: move from descriptive ("here's an anomaly")
    # to prescriptive ("cutting dining spend by 15% gets your runway back
    # over 90 days"). Deliberately not an ML model -- see
    # _compute_recommendations' docstring for why a transparent rules engine
    # is the more defensible choice here. Uses the latest month regardless
    # of the date-range picker below, same as the KPI row above: this is a
    # "what should I do right now" panel, not something you'd browse
    # historically.
    st.subheader("\U0001F4A1 Prescriptive Recommendations")
    with st.container(border=True):
        cut_pct = st.slider(
            "Hypothetical cut applied to top discretionary/variable categories "
            "not already over budget",
            min_value=5, max_value=30, value=15, step=5, key="rec_cut_pct",
        )
        recommendations = _compute_recommendations(
            category_spend, budget_vs_actual, current_balance, avg_daily_burn, forecast, cut_pct,
        )
        if not recommendations:
            st.info("Nothing stands out this month -- no budgets exceeded and no notable "
                     "discretionary/variable spend to trim.")
        else:
            for i, rec in enumerate(recommendations):
                st.markdown(f"**{rec['headline']}**")
                st.caption(f"{rec['action']} → frees up ~${rec['monthly_savings']:,.0f}/month")
                m1, m2, m3 = st.columns(3)
                m1.metric("Monthly savings", f"${rec['monthly_savings']:,.0f}")
                if rec["old_runway"] is not None:
                    old_txt = "∞" if rec["old_runway"] == float("inf") else f"{rec['old_runway']:,.0f}d"
                    new_txt = "∞" if rec["new_runway"] == float("inf") else f"{rec['new_runway']:,.0f}d"
                    if rec["new_runway"] == float("inf"):
                        delta_txt = "no longer burning cash"
                    else:
                        diff_days = round(rec["new_runway"] - rec["old_runway"])
                        # round() can produce -0 for a negligible negative
                        # diff (e.g. a $5 cut against a huge burn rate);
                        # "-0" reads as a display bug, so normalize it.
                        delta_txt = "no meaningful change" if diff_days == 0 else f"{diff_days:+,} days"
                    m2.metric("Runway", f"{old_txt} → {new_txt}", delta=delta_txt)
                else:
                    m2.metric("Runway", "n/a", delta=rec["runway_na_reason"])
                if rec["old_forecast_balance"] is not None:
                    m3.metric(
                        "30-day forecasted balance",
                        f"${rec['new_forecast_balance']:,.0f}",
                        delta=f"+${rec['monthly_savings']:,.0f} vs ${rec['old_forecast_balance']:,.0f} shown above",
                    )
                else:
                    m3.metric("30-day forecasted balance", "n/a", delta="no forecast yet")
                if i < len(recommendations) - 1:
                    st.divider()
        st.caption("Rules-based, not a model: every number above is plain arithmetic from the "
                    "same tables behind the KPIs, the category chart, and the forecast, so you "
                    "can check the math yourself. Over-budget rows use the actual overage; "
                    "everything else uses the hypothetical cut % set above.")

    # --- Cash flow trend + forecast ---------------------------------------
    # These used to share one chart (monthly bars + daily forecast line on a
    # second y-axis). Two problems with that: the bars are monthly and the
    # forecast is daily, so 30 daily points get squeezed into a sliver a few
    # pixels wide at the end of an 18-month axis -- any real day-to-day
    # movement in the forecast then reads as a jagged spike. And the two
    # series don't even share units (net flow vs. balance), so the shared
    # axis was misleading on top of being cramped. Split into two charts,
    # each on its own axis and its own time scale, instead.
    st.subheader("Cash Flow: History & 30-Day Forecast")
    hist_col, forecast_col = st.columns(2)

    with hist_col, st.container(border=True):
        st.caption("Historical Net Flow (monthly)")
        if not monthly.empty:
            # Net flow sign means good/bad, so it uses the fixed status
            # colors (good/critical) rather than an ad hoc categorical
            # color -- paired with a two-item legend so color never
            # carries the meaning alone.
            bar_colors = [COLOR["critical"] if v < 0 else COLOR["good"] for v in monthly["net_flow"]]
            fig_hist = go.Figure()
            fig_hist.add_trace(go.Bar(
                x=monthly["month"], y=monthly["net_flow"], marker_color=bar_colors,
                showlegend=False, hovertemplate="%{x}<br>$%{y:,.0f}<extra></extra>",
            ))
            # Two invisible marker traces purely to carry the icon+label
            # legend for the status colors used above.
            fig_hist.add_trace(go.Bar(x=[None], y=[None], marker_color=COLOR["good"], name="▲ Inflow (net positive)"))
            fig_hist.add_trace(go.Bar(x=[None], y=[None], marker_color=COLOR["critical"], name="▼ Outflow (net negative)"))
            fig_hist.update_layout(
                xaxis_title="", yaxis_title="Net Flow ($)",
                legend=dict(orientation="h", yanchor="bottom", y=1.02, xanchor="left", x=0, font=dict(size=11)),
                bargap=0.25,
            )
            base_layout(fig_hist)
            st.plotly_chart(fig_hist, use_container_width=True, config={"displayModeBar": False})
        else:
            st.info("No historical data yet.")

    with forecast_col, st.container(border=True):
        st.caption("30-Day Balance Forecast (daily)")
        if not forecast.empty:
            fig_fc = go.Figure()
            fig_fc.add_trace(go.Scatter(
                x=forecast["forecast_date"], y=forecast["predicted_balance"],
                name="Forecasted Balance", mode="lines+markers",
                line=dict(color=COLOR["good"], width=2.5),
                marker=dict(size=6, color=COLOR["good"]),
                fill="tozeroy", fillcolor="rgba(34, 197, 94, 0.12)",
                hovertemplate="%{x}<br>$%{y:,.0f}<extra></extra>",
            ))
            fig_fc.add_hline(y=current_balance, line_dash="dot", line_color=COLOR["muted"],
                              annotation_text="Current balance", annotation_position="bottom right",
                              annotation_font_color=COLOR["muted"])
            fig_fc.update_layout(xaxis_title="", yaxis_title="Forecasted Balance ($)", showlegend=False)
            base_layout(fig_fc)
            st.plotly_chart(fig_fc, use_container_width=True, config={"displayModeBar": False})
        else:
            st.info("No forecast data yet.")

    # --- Date range filter ---------------------------------------------------
    # Feeds the two sections below (Spend by Category, Budget vs. Actual),
    # which used to be locked to whatever "latest month" happened to be in
    # the data -- no way to look at a different month or a wider window.
    # Defaults to the latest available month so the page looks the same as
    # before until you touch it. The KPI row above (avg daily burn, runway)
    # deliberately stays a fixed "as of today" snapshot rather than
    # following this filter -- those are current-status numbers, not a
    # report you'd browse historically.
    if not monthly.empty:
        min_month_date = datetime.strptime(monthly["month"].min(), "%Y-%m").date()
        max_month_date = datetime.strptime(monthly["month"].max(), "%Y-%m").date()
        date_range = st.date_input(
            "Date range (filters Spend by Category and Budget vs. Actual below)",
            value=(max_month_date, max_month_date),
            min_value=min_month_date, max_value=max_month_date,
        )
        if isinstance(date_range, (tuple, list)) and len(date_range) == 2:
            range_start, range_end = date_range
        else:
            single = date_range[0] if isinstance(date_range, (tuple, list)) else date_range
            range_start = range_end = single
        if range_start > range_end:
            range_start, range_end = range_end, range_start
        start_month = range_start.strftime("%Y-%m")
        end_month = range_end.strftime("%Y-%m")
    else:
        start_month, end_month = "0000-00", "9999-99"
    range_label = start_month if start_month == end_month else f"{start_month} → {end_month}"

    category_spend_filtered = category_spend[
        (category_spend["month"] >= start_month) & (category_spend["month"] <= end_month)
    ]
    budget_vs_actual_filtered = budget_vs_actual[
        (budget_vs_actual["month"] >= start_month) & (budget_vs_actual["month"] <= end_month)
    ]

    # --- Category breakdown ------------------------------------------------
    # A pie chart doesn't hold up once there are more than a handful of
    # categories (this data has up to ~14): slice angles get too thin to
    # compare and color would have to carry pure identity across too many
    # slots. This is really a magnitude-comparison job ("which categories
    # cost the most"), so it becomes a single-hue horizontal bar ranked by
    # spend, with the $ amount labeled directly on each bar.
    st.subheader("Spend by Category")
    with st.container(border=True):
        st.caption(f"Showing: {range_label} · click a bar to see its transactions")
        if not category_spend_filtered.empty:
            latest = (
                category_spend_filtered.groupby("category_name", as_index=False)["total_amount"].sum()
            )
            latest = latest.sort_values("total_amount", ascending=True)

            n = len(latest)
            if n > 1:
                ramp_idx = [round(i * (len(SEQUENTIAL_GREEN) - 1) / (n - 1)) for i in range(n)]
            else:
                ramp_idx = [len(SEQUENTIAL_GREEN) - 1]
            bar_colors = [SEQUENTIAL_GREEN[i] for i in ramp_idx]

            max_spend = float(latest["total_amount"].max())

            fig_cat = go.Figure()
            fig_cat.add_trace(go.Bar(
                x=latest["total_amount"], y=latest["category_name"], orientation="h",
                marker_color=bar_colors,
                text=[f"${v:,.0f}" for v in latest["total_amount"]],
                textposition="outside", textfont=dict(color=COLOR["text"], size=12),
                cliponaxis=False,
                hovertemplate="%{y}<br>$%{x:,.0f}<extra></extra>",
            ))
            fig_cat.update_layout(
                xaxis_title="Total Spend ($)", yaxis_title="",
                showlegend=False, bargap=0.3,
            )
            # Headroom past the longest bar so its outside label isn't
            # clipped by the plot edge, and a right margin sized the same way.
            fig_cat.update_xaxes(showgrid=True, range=[0, max_spend * 1.22])
            base_layout(fig_cat, height=max(300, 34 * n))
            fig_cat.update_layout(margin=dict(l=10, r=30, t=10, b=10))
            # on_select="rerun" turns a bar click into a normal Streamlit
            # rerun with the clicked point available below -- no custom JS
            # needed, just Streamlit's native chart-selection event (1.35+).
            cat_event = st.plotly_chart(
                fig_cat, use_container_width=True, config={"displayModeBar": False},
                on_select="rerun", selection_mode="points", key="category_chart",
            )

            selected_category = None
            if cat_event and cat_event["selection"]["points"]:
                selected_category = cat_event["selection"]["points"][0].get("y")

            if selected_category:
                drill = load_table("category_transactions", {
                    "account_id": account_id, "category_name": selected_category,
                    "start_month": start_month, "end_month": end_month,
                })
                st.markdown(f"**{selected_category} transactions — {range_label}**")
                if not drill.empty:
                    st.dataframe(
                        drill.rename(columns={
                            "txn_date": "Date", "merchant_name": "Merchant",
                            "amount": "Amount", "is_recurring": "Recurring",
                        }).style.format({"Amount": "${:,.2f}"}),
                        width="stretch",
                    )
                else:
                    st.info("No transactions found for this category in the selected range.")
        else:
            st.info("No category spend data for the selected date range.")

    # --- Budget vs. actual ---------------------------------------------------
    # Status (over/under budget) is what matters here, not raw category
    # identity, so "Actual" is split into two same-hued-family traces (good/
    # critical) rather than one trace colored per-bar -- a single bar trace
    # can't carry two different legend colors cleanly, and color needs to
    # follow a fixed entity (the status), never vary within one legend swatch.
    st.subheader("Budget vs. Actual")
    with st.container(border=True):
        st.caption(f"Showing: {range_label}")
        if not budget_vs_actual_filtered.empty:
            bva = (
                budget_vs_actual_filtered
                .groupby("category_name", as_index=False)[["budgeted_amount", "actual_amount"]]
                .sum()
            )
            bva = bva.sort_values("budgeted_amount", ascending=True)
            within = bva[bva["actual_amount"] <= bva["budgeted_amount"]]
            over = bva[bva["actual_amount"] > bva["budgeted_amount"]]

            fig_bva = go.Figure()
            fig_bva.add_trace(go.Bar(
                x=bva["budgeted_amount"], y=bva["category_name"], orientation="h",
                name="Budgeted", marker_color=COLOR["muted"], opacity=0.45,
                hovertemplate="%{y}<br>Budgeted: $%{x:,.0f}<extra></extra>",
            ))
            fig_bva.add_trace(go.Bar(
                x=within["actual_amount"], y=within["category_name"], orientation="h",
                name="Actual (within budget)", marker_color=COLOR["good"],
                hovertemplate="%{y}<br>Actual: $%{x:,.0f}<extra></extra>",
            ))
            fig_bva.add_trace(go.Bar(
                x=over["actual_amount"], y=over["category_name"], orientation="h",
                name="Actual (over budget)", marker_color=COLOR["critical"],
                hovertemplate="%{y}<br>Actual: $%{x:,.0f}<extra></extra>",
            ))
            fig_bva.update_layout(
                barmode="group", xaxis_title="Amount ($)", yaxis_title="",
                legend=dict(orientation="h", yanchor="bottom", y=1.02, xanchor="left", x=0, font=dict(size=11)),
            )
            base_layout(fig_bva, height=max(300, 42 * len(bva)))
            st.plotly_chart(fig_bva, use_container_width=True, config={"displayModeBar": False})

            if not over.empty:
                names = ", ".join(over["category_name"])
                st.warning(f"⚠️ Over budget in {range_label}: {names}")
        else:
            st.info("No budgets set for the selected date range.")

    # --- Recurring & subscriptions --------------------------------------------
    st.subheader("\U0001F501 Recurring & Subscriptions")
    with st.container(border=True):
        if not recurring.empty:
            rec = recurring.copy()
            rec["amount_changed"] = (
                (rec["typical_amount"] > 0)
                & ((rec["last_amount"] - rec["typical_amount"]).abs() / rec["typical_amount"] > 0.05)
            )
            display = rec.rename(columns={
                "merchant_name": "Merchant",
                "typical_amount": "Typical Amount",
                "last_amount": "Last Amount",
                "last_txn_date": "Last Charged",
                "occurrence_count": "Charges Seen",
            })
            display["Changed?"] = display["amount_changed"].map(lambda v: "⚠️ Changed" if v else "—")
            st.dataframe(
                display[["Merchant", "Typical Amount", "Last Amount", "Last Charged", "Charges Seen", "Changed?"]]
                    .style.format({"Typical Amount": "${:,.2f}", "Last Amount": "${:,.2f}"}),
                width="stretch",
            )
            changed = rec[rec["amount_changed"]]
            if not changed.empty:
                names = ", ".join(changed["merchant_name"])
                st.warning(f"⚠️ Charge amount changed recently for: {names}")
        else:
            st.info("No recurring transactions detected yet.")

    # --- Anomalies -----------------------------------------------------------
    st.subheader("\U0001F6A9 Flagged Transactions (Isolation Forest)")
    if not anomalies.empty:
        st.dataframe(
            anomalies.style.format({"amount": "${:,.2f}", "anomaly_score": "{:.2f}"}),
            width="stretch",
        )
        st.download_button(
            "⬇ Download flagged transactions (CSV)",
            data=anomalies.to_csv(index=False).encode("utf-8"),
            file_name=f"cashpulse_flagged_transactions_{_slug(account_name)}.csv",
            mime="text/csv",
            key="download_anomalies",
        )
    else:
        st.info("No anomalies flagged yet.")

    # --- Manage transactions --------------------------------------------------
    # See _get_write_conn()'s docstring for why this is SQLite-tier-only.
    st.subheader("✏️ Manage Transactions")
    if BACKEND != "sqlite":
        st.info("Manual entry/editing is available on the local SQLite tier only. "
                 "The cloud tier's dbt pipeline rebuilds `analytics.*` from `raw.*` "
                 "on every run, so a direct write here would just be overwritten "
                 "on the next run -- see ROADMAP.md.")
    else:
        categories_df = load_table("categories")
        merchants_df = load_table("merchants")
        category_by_id = dict(zip(categories_df["category_id"], categories_df["category_name"]))
        category_names = categories_df["category_name"].tolist()
        merchant_names = merchants_df["merchant_name"].tolist()
        merchant_default_cat = dict(zip(merchants_df["merchant_name"], merchants_df["default_category_id"]))

        add_tab, edit_tab, rules_tab = st.tabs(
            ["➕ Add transaction", "\U0001F5C2️ Edit / delete", "\U0001F3f7️ Category rules"]
        )

        # --- Add ---------------------------------------------------------
        with add_tab:
            c1, c2, c3 = st.columns(3)
            with c1:
                new_date = st.date_input("Date", value=datetime.today(), key="new_txn_date")
                new_type = st.selectbox("Type", ["debit", "credit"], key="new_txn_type")
            with c2:
                new_amount = st.number_input(
                    "Amount ($)", min_value=0.01, step=1.0, format="%.2f", key="new_txn_amount"
                )
                merchant_choice = st.selectbox(
                    "Merchant", ["(none)"] + sorted(merchant_names) + ["+ Add new merchant"],
                    key="new_txn_merchant",
                )
            new_merchant_name = None
            if merchant_choice == "+ Add new merchant":
                new_merchant_name = st.text_input("New merchant name", key="new_txn_new_merchant")

            # Auto-categorization, part 1: suggest (never silently force) a
            # category the moment a known merchant is picked.
            suggested_category = None
            if merchant_choice not in ("(none)", "+ Add new merchant"):
                suggested_category = category_by_id.get(merchant_default_cat.get(merchant_choice))

            # A selectbox's `index=` argument is only honored the very first
            # time a widget with that `key` is created -- on every later
            # rerun Streamlit keeps whatever's already in session_state for
            # that key and silently ignores `index=`. So changing merchants
            # and expecting the category dropdown to visually follow needs
            # an explicit session_state write *before* the widget is
            # instantiated, guarded so it only fires when the merchant
            # selection itself just changed -- otherwise it would stomp on
            # a manual category override every time an unrelated widget
            # (e.g. the description field) triggers a rerun.
            if st.session_state.get("_new_txn_category_synced_for") != merchant_choice:
                if suggested_category:
                    st.session_state["new_txn_category"] = suggested_category
                st.session_state["_new_txn_category_synced_for"] = merchant_choice

            with c3:
                new_category = st.selectbox("Category", category_names, key="new_txn_category")
                new_recurring = st.checkbox("Recurring", key="new_txn_recurring")

            new_description = st.text_input("Description (optional)", key="new_txn_description")

            if suggested_category:
                st.caption(f"ℹ️ Auto-suggested **{suggested_category}** from this "
                            "merchant's history -- change it above if this one's different.")
            elif merchant_choice == "+ Add new merchant" and new_merchant_name:
                st.caption("New merchant -- the category you pick above will be remembered "
                            "as its default from now on (auto-categorization, part 2).")

            if st.button("Add transaction", type="primary", key="add_txn_submit"):
                merchant_to_use = (
                    _clean_text(new_merchant_name) if merchant_choice == "+ Add new merchant"
                    else (merchant_choice if merchant_choice != "(none)" else None)
                )
                if merchant_choice == "+ Add new merchant" and not merchant_to_use:
                    st.error("Enter a name for the new merchant, or choose an existing one.")
                else:
                    conn = _get_write_conn()
                    try:
                        category_id = int(
                            categories_df.loc[categories_df["category_name"] == new_category, "category_id"].iloc[0]
                        )
                        merchant_id = (
                            _get_or_create_merchant(conn, merchant_to_use, category_id)
                            if merchant_to_use else None
                        )
                        conn.execute(
                            """INSERT INTO transactions
                               (account_id, merchant_id, category_id, txn_date, amount,
                                txn_type, description, is_recurring)
                               VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
                            (account_id, merchant_id, category_id, new_date.isoformat(),
                             round(abs(float(new_amount)), 2), new_type,
                             _clean_text(new_description), int(new_recurring)),
                        )
                        conn.commit()
                        st.success(f"Added {new_type} of ${new_amount:,.2f} on {new_date.isoformat()}.")
                        _invalidate_and_rerun()
                    finally:
                        conn.close()

        # --- Edit / delete -------------------------------------------------
        with edit_tab:
            all_txns = load_table("all_transactions", {"account_id": account_id})
            if all_txns.empty:
                st.info("No transactions yet for this account.")
            else:
                display_txns = all_txns.rename(columns={
                    "txn_date": "Date", "merchant_name": "Merchant", "category_name": "Category",
                    "amount": "Amount", "txn_type": "Type", "description": "Description",
                    "is_recurring": "Recurring",
                }).set_index("transaction_id")
                display_txns["Date"] = pd.to_datetime(display_txns["Date"]).dt.date
                display_txns["Recurring"] = display_txns["Recurring"].astype(bool)
                display_txns["Delete?"] = False

                st.caption(f"Showing the {len(display_txns):,} most recent transactions for "
                            "this account. Edit a cell, or check “Delete?”, then save.")
                edited = st.data_editor(
                    display_txns,
                    column_config={
                        "Category": st.column_config.SelectboxColumn(options=category_names, required=True),
                        "Type": st.column_config.SelectboxColumn(options=["debit", "credit"], required=True),
                        "Amount": st.column_config.NumberColumn(format="$%.2f", min_value=0.01),
                        "Date": st.column_config.DateColumn(format="YYYY-MM-DD", required=True),
                        "Delete?": st.column_config.CheckboxColumn(
                            help="Check, then Save changes, to permanently delete this row."
                        ),
                    },
                    num_rows="fixed",
                    width="stretch",
                    key="edit_txn_editor",
                )
                if st.button("\U0001F4be Save changes", key="save_txn_edits"):
                    conn = _get_write_conn()
                    try:
                        n_deleted = n_updated = 0
                        for txn_id, row in edited.iterrows():
                            if row["Delete?"]:
                                conn.execute(
                                    "DELETE FROM transactions WHERE transaction_id = ?", (int(txn_id),)
                                )
                                n_deleted += 1
                                continue
                            category_id = int(
                                categories_df.loc[categories_df["category_name"] == row["Category"], "category_id"].iloc[0]
                            )
                            merchant_name = _clean_text(row["Merchant"])
                            merchant_id = (
                                _get_or_create_merchant(conn, merchant_name, category_id)
                                if merchant_name else None
                            )
                            conn.execute(
                                """UPDATE transactions
                                   SET txn_date = ?, merchant_id = ?, category_id = ?, amount = ?,
                                       txn_type = ?, description = ?, is_recurring = ?
                                   WHERE transaction_id = ?""",
                                (pd.Timestamp(row["Date"]).strftime("%Y-%m-%d"), merchant_id, category_id,
                                 round(abs(float(row["Amount"])), 2), row["Type"],
                                 _clean_text(row["Description"]), int(bool(row["Recurring"])), int(txn_id)),
                            )
                            n_updated += 1
                        conn.commit()
                        st.success(f"Saved: {n_updated} updated, {n_deleted} deleted.")
                        _invalidate_and_rerun()
                    finally:
                        conn.close()

        # --- Category rules --------------------------------------------------
        with rules_tab:
            st.caption("Each merchant's default category -- the suggestion shown on the "
                        "Add tab when you pick that merchant. Editing it here only changes "
                        "the suggestion going forward, not any past transactions.")
            rules_df = merchants_df.copy()
            rules_df["Default Category"] = rules_df["default_category_id"].map(category_by_id)
            rules_df = rules_df.rename(columns={"merchant_name": "Merchant"})
            rules_df = rules_df.set_index("merchant_id")[["Merchant", "Default Category"]]
            edited_rules = st.data_editor(
                rules_df,
                column_config={
                    "Merchant": st.column_config.TextColumn(disabled=True),
                    "Default Category": st.column_config.SelectboxColumn(
                        options=category_names, required=True
                    ),
                },
                num_rows="fixed",
                width="stretch",
                key="rules_editor",
            )
            if st.button("\U0001F4be Save category rules", key="save_rules"):
                conn = _get_write_conn()
                try:
                    n = 0
                    for merchant_id, row in edited_rules.iterrows():
                        new_cat_id = int(
                            categories_df.loc[categories_df["category_name"] == row["Default Category"], "category_id"].iloc[0]
                        )
                        conn.execute(
                            "UPDATE merchants SET default_category_id = ? WHERE merchant_id = ?",
                            (new_cat_id, int(merchant_id)),
                        )
                        n += 1
                    conn.commit()
                    st.success(f"Updated {n} merchant categor{'y' if n == 1 else 'ies'}.")
                    _invalidate_and_rerun()
                finally:
                    conn.close()

    render_integrations()


if __name__ == "__main__":
    main()
